// Builds every brand output from brand/tokens.json and brand/logo/logo.svg.
// Run from the repo root:   npm run brand
// sharp comes with Next, so nothing needs installing.
//
// Writes (never edit these by hand):
//   app/brand.css            palette, theme roles, @property initial values, pupil size
//   app/brand.ts             the few values TypeScript needs (browser bar, pupil)
//   public/logo-text.svg     the nav logo
//   public/favicon.svg, app/favicon.ico, app/apple-icon.png, public/logo.png
//   brand/exports/           logo PNG/GIFs and the LinkedIn company cover
//   brand/guidelines/DESIGN.md   the blocks between <!-- brand:… --> markers
// Fails (exit 1) if any check in tokens.json "contrast" drops below its minimum.
import sharp from "sharp";
import { readFileSync, writeFileSync } from "node:fs";

const T = JSON.parse(readFileSync("brand/tokens.json", "utf8"));
const OUT = "brand/exports";
const HEAD = "GENERATED by brand/build.mjs from brand/tokens.json. Do not edit; run `npm run brand`.";

// ── colour helpers ──
/** "green-800" → "#0e372d" */
function hex(ref) {
  const i = ref.lastIndexOf("-");
  const c = T.color[ref.slice(0, i)]?.[ref.slice(i + 1)];
  if (!c) throw new Error(`brand/tokens.json: no colour "${ref}"`);
  return c.hex.toLowerCase();
}
const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const lum = (h) => {
  const [r, g, b] = rgb(h).map(lin);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((m, n) => n - m);
  return (x + 0.05) / (y + 0.05);
};
/** a role or palette ref, resolved for a theme */
const resolve = (ref, theme) => (T.roles[ref] ? hex(T.roles[ref][theme]) : hex(ref));
const swatches = Object.entries(T.color).flatMap(([fam, steps]) =>
  Object.entries(steps)
    .sort(([a], [b]) => b - a)
    .map(([step, c]) => ({ name: `${fam}-${step}`, ...c })),
);

// the themes every role is given, in tokens.json's order: dark first (the
// default), then light, then any others (the bridge)
const THEMES = Object.keys(Object.values(T.roles)[0]).filter((k) => k !== "use");
const title = (t) => t[0].toUpperCase() + t.slice(1);

// ── contrast checks ──
const checks = T.contrast.map((c) => ({
  ...c,
  ...Object.fromEntries(THEMES.map((t) => [t, ratio(resolve(c.fg, t), resolve(c.bg, t))])),
}));
const failed = checks.filter((c) => THEMES.some((t) => c[t] < c.min));

// ── app/brand.css and app/brand.ts ──
const pupilH = T.logo.pupilRy / T.logo.eyeRy;
const pct = (n) => `${+(n * 100).toFixed(1)}%`;
const css = `/* ${HEAD} */

/* Theme roles are registered so ThemeGates.tsx's swaps fade; that needs
   literal initial values: the dark theme's. */
${Object.keys(T.roles)
  .map((r) => `@property --${r} {\n  syntax: "<color>";\n  inherits: true;\n  initial-value: ${hex(T.roles[r].dark)};\n}`)
  .join("\n")}

@layer tokens {
  :root {
${swatches.map((s) => `    --${s.name}: ${s.hex}; /* ${s.use} */`).join("\n")}

    /* the logo's pupil inside its almond (rx ${T.logo.pupilRx}, ry ${T.logo.pupilRy} of ${T.logo.eyeRy}) */
    --pupil-height: ${pct(pupilH)};
    --pupil-top: ${pct((1 - pupilH) / 2)};
  }
${THEMES.map(
  (t, i) =>
    `  ${i ? `:root[data-theme="${t}"]` : ":root"} {\n${Object.entries(T.roles)
      .map(([r, v]) => `    --${r}: var(--${v[t]});`)
      .join("\n")}\n  }`,
).join("\n")}
}
`;
writeFileSync("app/brand.css", css);
writeFileSync(
  "app/brand.ts",
  `// ${HEAD}\n\n/** the browser bar (meta theme-color can't read CSS variables) */\nexport const BROWSER_BAR = "${hex(T.browserBar)}";\n/** the logo's pupil height as a share of its eye's */\nexport const PUPIL_HEIGHT = ${+pupilH.toFixed(4)};\n`,
);

// ── the logo ──
const matrix = (h) => {
  const [r, g, b] = rgb(h);
  return `0 0 0 0 ${r.toFixed(6)} 0 0 0 0 ${g.toFixed(6)} 0 0 0 0 ${b.toFixed(6)} 0 0 0 0.3 0`;
};
const SRC = readFileSync("brand/logo/logo.svg", "utf8").replace(/\{logo\.(\w+)(:matrix)?\}/g, (_, k, m) => {
  const v = T.logo[k];
  if (v === undefined) throw new Error(`brand/logo/logo.svg: no logo.${k} in tokens.json`);
  if (typeof v === "number") return String(v);
  return m ? matrix(hex(v)) : hex(v).toUpperCase();
});
writeFileSync("public/logo-text.svg", SRC);

const EYE_FILL = hex(T.logo.eye).toUpperCase();
const ALMOND = SRC.match(new RegExp(`<path d="([^"]+)" fill="${EYE_FILL}"/>`))[1];
const PUPIL = SRC.match(/<ellipse [^>]+\/>/)[0];
const CX = 200;
const CY = 84.375;
const EYE_W = 62; // almond, 169 → 231
const EYE_H = 31.25; // almond, 68.75 → 100

/** The logo's inner SVG with the pupil moved by (dx, dy), as fractions of
 *  EyeTracker.tsx's reach (30% of the eye's width, 12% of its height), and
 *  the eye squashed to `open` of its height, as its blink does. */
function logo(dx = 0, dy = 0, open = 1) {
  const eye =
    `<clipPath id="almond"><path d="${ALMOND}"/></clipPath>` +
    `<g transform="translate(${CX} ${CY}) scale(1 ${open}) translate(${-CX} ${-CY})">` +
    `<path d="${ALMOND}" fill="${EYE_FILL}"/>` +
    `<g clip-path="url(#almond)"><g transform="translate(${dx * EYE_W * 0.3} ${dy * EYE_H * 0.12})">${PUPIL}</g></g>` +
    `</g>`;
  return SRC.replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(`<path d="${ALMOND}" fill="${EYE_FILL}"/>`, "")
    .replace(PUPIL, eye);
}

/** A square tile: the logo at 150/180 of the side, centred on `bg`, as the
 *  apple icon has always been. No `bg` = the bare logo, transparent. */
function tile(bg, dx, dy, open) {
  const body = bg
    ? `<rect width="300" height="300" fill="${bg}"/><g transform="translate(25 25) scale(${150 / 180})">${logo(dx, dy, open)}</g>`
    : logo(dx, dy, open);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 300 300" width="300" height="300">${body}</svg>`;
}

const png = (svg, w, h = w, vw = 300) =>
  sharp(Buffer.from(svg), { density: (72 * w * 2) / vw }).resize(w, h).png().toBuffer();

// ── the look: a few glances and a blink, about 5s, looping ──
const ease = (t) => (t < 0.5 ? 4 * t * t * t : 1 - (-2 * t + 2) ** 3 / 2);
const KEYS = [
  // [ms, dx, dy]: glide between keys, hold where two keys share a pose
  [0, 0, 0.3],
  [700, 0, 0.3],
  [1300, -1, 0.2],
  [1900, -1, 0.2],
  [2700, 1, -0.1],
  [3300, 1, -0.1],
  [3800, 0, 0.3],
  [5000, 0, 0.3],
];
const BLINK_AT = 3900;
const BLINK_MS = 220;
const STEP = 40; // ms per frame (GIF delays are in 10ms steps)

function pose(ms) {
  let i = 0;
  while (i < KEYS.length - 2 && ms >= KEYS[i + 1][0]) i++;
  const [t0, x0, y0] = KEYS[i];
  const [t1, x1, y1] = KEYS[i + 1];
  const t = ease(Math.min(1, Math.max(0, (ms - t0) / (t1 - t0))));
  // the blink: shut to 8% at its middle and open again, ease-in-out
  const b = (ms - BLINK_AT) / BLINK_MS;
  const open = b > 0 && b < 1 ? 1 - 0.92 * ease(1 - Math.abs(2 * b - 1)) : 1;
  return [x0 + (x1 - x0) * t, y0 + (y1 - y0) * t, open];
}

async function gif(bg, size, file) {
  // consecutive identical frames merge into one longer frame
  const frames = [];
  for (let ms = 0; ms < KEYS.at(-1)[0]; ms += STEP) {
    const key = pose(ms).map((n) => n.toFixed(3)).join();
    if (frames.length && frames.at(-1).key === key) frames.at(-1).delay += STEP;
    else frames.push({ key, pose: pose(ms), delay: STEP });
  }
  const bufs = await Promise.all(frames.map((f) => png(tile(bg, ...f.pose), size)));
  await sharp(bufs, { join: { animated: true } })
    .gif({ delay: frames.map((f) => f.delay), loop: 0, effort: 10 })
    .toFile(`${OUT}/${file}`);
}

/** A .ico of PNG images, one per size. */
async function ico(svg, sizes, file) {
  const imgs = await Promise.all(sizes.map((s) => png(svg, s)));
  const head = Buffer.alloc(6 + 16 * sizes.length);
  head.writeUInt16LE(1, 2); // type: icon
  head.writeUInt16LE(sizes.length, 4);
  let offset = head.length;
  sizes.forEach((s, i) => {
    const e = 6 + 16 * i;
    head.writeUInt8(s % 256, e); // 256 is written as 0
    head.writeUInt8(s % 256, e + 1);
    head.writeUInt16LE(1, e + 4); // planes
    head.writeUInt16LE(32, e + 6); // bits per pixel
    head.writeUInt32LE(imgs[i].length, e + 8);
    head.writeUInt32LE(offset, e + 12);
    offset += imgs[i].length;
  });
  writeFileSync(file, Buffer.concat([head, ...imgs]));
}

const DARK = hex(T.logo.tile);
const LIGHT = hex(T.logo.lightTile);
writeFileSync(`${OUT}/logo-dark.png`, await png(tile(DARK), 1024));
writeFileSync(`${OUT}/logo-light.png`, await png(tile(LIGHT), 1024));
await gif(DARK, 512, "logo-dark.gif");
await gif(LIGHT, 512, "logo-light.gif");
writeFileSync("public/favicon.svg", tile(DARK) + "\n");
await ico(tile(DARK), [16, 32, 48], "app/favicon.ico");
writeFileSync("app/apple-icon.png", await png(tile(DARK), 180));
writeFileSync("public/logo.png", await png(tile(), 512));

// ── LinkedIn company cover: the vine (design canvas "A3 · Vine") ──
// 1584 × 268 artboard units = LinkedIn's 1128 × 191 cover at 1.4×.
function cover() {
  const L = T.linkedinCover;
  const W = 1584;
  const H = 268;
  const leaf = "M 0 0 C 5 -9, 17 -9, 24 0 C 17 9, 5 9, 0 0 Z"; // LeafConnector.tsx LEAF
  const bud = "M 0 0 q 13 13.5 24 0 q -11 -13.5 -24 0 z"; // LeafConnector.tsx BUD
  const at = (p, t) => {
    const u = 1 - t;
    const c = (i) => u * u * u * p[0][i] + 3 * u * u * t * p[1][i] + 3 * u * t * t * p[2][i] + t * t * t * p[3][i];
    const d = (i) => 3 * u * u * (p[1][i] - p[0][i]) + 6 * u * t * (p[2][i] - p[1][i]) + 3 * t * t * (p[3][i] - p[2][i]);
    return { x: c(0), y: c(1), a: (Math.atan2(d(1), d(0)) * 180) / Math.PI };
  };
  const stems = [
    { p: [[360, 300], [400, 150], [560, 40], [780, 34]], end: "bud", fill: L.warmBud }, // the one touch of warm
    { p: [[700, -30], [860, 110], [880, 250], [1130, 196]], end: "eye" },
    { p: [[1620, 236], [1470, 200], [1440, 40], [1250, 64]], end: "bud" },
  ];
  const s = L.leafSize / 26; // leaf units → px
  const vine = hex(L.vine);
  let body = "";
  for (const { p, end, fill = L.bud } of stems) {
    body += `<path d="M ${p[0]} C ${p[1]}, ${p[2]}, ${p[3]}" fill="none" stroke="${vine}" stroke-width="${L.strokeWidth}" stroke-linecap="round"/>`;
    for (let i = 0; i < L.leavesPerStem; i++) {
      const q = at(p, 0.18 + (0.68 * (i + 0.5)) / L.leavesPerStem);
      body += `<path d="${leaf}" transform="translate(${q.x.toFixed(1)} ${q.y.toFixed(1)}) rotate(${(q.a + (i % 2 ? 50 : -50)).toFixed(1)}) scale(${s.toFixed(3)})" fill="none" stroke="${vine}" stroke-width="${(L.strokeWidth / s).toFixed(3)}" stroke-linejoin="round"/>`;
    }
    const e = at(p, 1);
    if (end === "bud") {
      body += `<path d="${bud}" transform="translate(${e.x.toFixed(1)} ${e.y.toFixed(1)}) rotate(${e.a.toFixed(1)}) scale(${s.toFixed(3)})" fill="${hex(fill)}"/>`;
    } else {
      // the logo's eye, its back tip on the stem's end, turned along the stem
      const k = L.eyeSize / 68;
      body += `<g transform="translate(${e.x.toFixed(1)} ${e.y.toFixed(1)}) rotate(${e.a.toFixed(1)}) scale(${k.toFixed(4)}) translate(-169.3 -84.375)"><clipPath id="cover-eye"><path d="${ALMOND}"/></clipPath><path d="${ALMOND}" fill="${EYE_FILL}"/><g clip-path="url(#cover-eye)">${PUPIL}</g></g>`;
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}"><rect width="${W}" height="${H}" fill="${hex(L.ground)}"/>${body}</svg>`;
}
const COVER = cover();
writeFileSync(`${OUT}/linkedin-company-cover.svg`, COVER + "\n");
writeFileSync(`${OUT}/linkedin-company-cover.png`, await png(COVER, 2256, 382, 1584));

// ── guidelines: regenerate the marked blocks ──
const f2 = (n) => n.toFixed(2);
const blocks = {
  palette: [
    "| Token | Hex | Used for |",
    "|---|---|---|",
    ...swatches.map((s) => `| \`--${s.name}\` | \`${s.hex}\` | ${s.use} |`),
  ].join("\n"),
  roles: [
    `| Role | ${THEMES.map((t, i) => title(t) + (i ? "" : " (default)")).join(" | ")} | Used for |`,
    `|---|${THEMES.map(() => "---|").join("")}---|`,
    ...Object.entries(T.roles).map(([r, v]) => `| \`--${r}\` | ${THEMES.map((t) => v[t]).join(" | ")} | ${v.use} |`),
  ].join("\n"),
  contrast: [
    `| Check | ${THEMES.map(title).join(" | ")} | Minimum |`,
    `|---|${THEMES.map(() => "---|").join("")}---|`,
    ...checks.map((c) => `| ${c.name} | ${THEMES.map((t) => f2(c[t])).join(" | ")} | ${c.min} |`),
  ].join("\n"),
  logo: `The logo is drawn in \`${T.logo.leaf}\` (\`${hex(T.logo.leaf)}\`), with a \`${T.logo.eye}\` eye and a \`${T.logo.pupil}\` pupil (rx ${T.logo.pupilRx}, ry ${T.logo.pupilRy}: ${pct(pupilH)} of the eye's height). The tile is \`${T.logo.tile}\`.`,
};
const DOC = "brand/guidelines/DESIGN.md";
let doc = readFileSync(DOC, "utf8");
for (const [k, v] of Object.entries(blocks)) {
  const re = new RegExp(`(<!-- brand:${k} -->)[\\s\\S]*?(<!-- /brand:${k} -->)`);
  if (!re.test(doc)) throw new Error(`${DOC}: missing <!-- brand:${k} --> block`);
  doc = doc.replace(re, `$1\n${v}\n$2`);
}
writeFileSync(DOC, doc);

// ── report ──
for (const c of checks)
  console.log(
    `${THEMES.some((t) => c[t] < c.min) ? "✗" : "✓"} ${c.name}: ${THEMES.map((t) => `${f2(c[t])} ${t}`).join(", ")} (min ${c.min})`,
  );
if (failed.length) {
  console.error(`\n${failed.length} contrast check(s) below minimum. Outputs were written; fix tokens.json and rerun.`);
  process.exit(1);
}
console.log("brand: done");
