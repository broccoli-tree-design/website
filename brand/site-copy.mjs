// Writes the site's current words, section by section, to
// brand/exports/site-copy.md, read from the rendered page (production by
// default, so it matches main). The Claude Design system carries it as its
// "Site copy" section, so new boards start from today's copy, not an old board's.
//
//   npm run site-copy                          from https://www.broccolitree.design
//   npm run site-copy -- http://localhost:3000 from a dev server (a branch's copy)

import { writeFileSync } from "node:fs";
import { execSync } from "node:child_process";

const URL_ = process.argv[2] || "https://www.broccolitree.design/";
const OUT = "brand/exports/site-copy.md";

const res = await fetch(URL_);
if (!res.ok) throw new Error(`${URL_}: HTTP ${res.status}`);
const html = await res.text();

const ENT = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " " };
const decode = (s) =>
  s.replace(/&(#x[0-9a-f]+|#\d+|\w+);/gi, (m, e) =>
    e[0] === "#" ? String.fromCodePoint(e[1] === "x" || e[1] === "X" ? parseInt(e.slice(2), 16) : +e.slice(1)) : ENT[e] ?? m,
  );

const VOID = new Set(["img", "br", "hr", "input", "meta", "link", "source", "path", "rect", "circle", "line", "use"]);

/** Drops every element marked aria-hidden="true": decoration and the scroll
 *  scenes' drawn copies of the cards, which would repeat the real words. */
function dropHidden(s) {
  let out = "", i = 0;
  const tag = /<(\/?)([a-zA-Z][\w-]*)\b([^>]*?)(\/?)>/g;
  for (let m; (m = tag.exec(s)); ) {
    if (m[1] || m[4] || VOID.has(m[2].toLowerCase()) || !/aria-hidden="true"/.test(m[3])) continue;
    out += s.slice(i, m.index);
    let depth = 1;
    const same = new RegExp(`<(/?)${m[2]}\\b[^>]*?(/?)>`, "g");
    same.lastIndex = tag.lastIndex;
    for (let n; depth && (n = same.exec(s)); ) if (!n[2]) depth += n[1] ? -1 : 1;
    i = tag.lastIndex = same.lastIndex || s.length;
  }
  return out + s.slice(i);
}

/** One section's HTML → bullet lines of its visible words. */
function words(part) {
  let s = dropHidden(part)
    .replace(/<(em|i|b|strong)\b[^>]*>\s*<\/\1>/gi, " ")
    .replace(/<(svg|script|style|noscript|template)\b[\s\S]*?<\/\1>/gi, "")
    .replace(/<img\b[^>]*?alt="([^"]*)"[^>]*>/gi, (_, alt) => (alt ? `\n- image: ${alt}\n` : ""))
    .replace(/<span[^>]*class="[^"]*\btext-label\b[^"]*"[^>]*>([\s\S]*?)<\/span>/gi, "\n- `label` $1\n")
    .replace(/<(h[1-6])\b[^>]*>/gi, (_, h) => `\n- \`${h.toLowerCase()}\` `)
    .replace(/<\/h[1-6]>/gi, "\n")
    .replace(/<button\b[^>]*aria-label="([^"]*)"[^>]*>\s*<\/button>/gi, "")
    .replace(/<a\b[^>]*href="([^"]*)"[^>]*>([\s\S]*?)<\/a>/gi, (_, href, t) => {
      const text = t.replace(/<[^>]+>/g, "").trim();
      return text ? `[${text}](${href})` : "";
    })
    .replace(/<\/?(em|i)\b[^>]*>/gi, "*")
    .replace(/<\/?(b|strong)\b[^>]*>/gi, "**")
    .replace(/<span[^>]*class="[^"]*\btext-[^"]*"[^>]*>/gi, "\n")
    .replace(/<\/?span\b[^>]*>/gi, "")
    .replace(/<br\s*\/?>/gi, " / ")
    .replace(/<\/?(div|p|li|ul|ol|button|figure|figcaption|header|nav|section|footer|dl|dt|dd)\b[^>]*>/gi, "\n")
    .replace(/<[^>]+>/g, " ");
  const lines = decode(s)
    .split("\n")
    .map((l) =>
      l
        .replace(/\s+/g, " ")
        .replace(/ ([.,;:!?)])/g, "$1")
        .trim(),
    )
    .filter((l) => l && l !== "-" && !/^- `\w+`$/.test(l))
    .map((l) => (l.startsWith("- ") ? l : `- ${l}`));
  return lines.filter((l, i) => l !== lines[i - 1]).join("\n");
}

const parts = [];
const nav = html.match(/<nav\b[\s\S]*?<\/nav>/i);
if (nav) parts.push(["Nav", "", nav[0]]);
for (const m of html.matchAll(/<(section|footer)\b([^>]*)>([\s\S]*?)<\/\1>/gi)) {
  const attr = (k) => (m[2].match(new RegExp(`${k}="([^"]*)"`)) || [])[1] || "";
  const name = attr("id") || attr("class").split(" ").filter((c) => c !== "grid").join(" ") || m[1];
  parts.push([name, attr("data-gate"), m[3]]);
}
if (parts.length < 3) throw new Error(`${URL_}: found only ${parts.length} sections; has the page structure changed?`);

let commit = "";
try {
  commit = execSync("git rev-parse --short origin/main", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
} catch {}

const md = `# Site copy

The words on the live homepage today, top to bottom, read from ${URL_}${
  commit ? ` (main at ${commit})` : ""
} on ${new Date().toISOString().slice(0, 10)}. Generated by \`npm run site-copy\` in the site repo: don't edit it here.

**Draw every board from this copy, not from an older board or canvas.** Boards are drawings: they keep the words they were drawn with, and the site has moved on since many of them. If a board's words differ from these, these are current.

How to read it: each section names its theme (dark, light, bridge). \`h2\`, \`h3\` and \`label\` mark headings and small uppercase labels; *italic* is an \`em\` accent; \` / \` is a forced line break; links show where they go; images show their alt text.

${parts.map(([name, gate, body]) => `## ${name}${gate ? ` · ${gate}` : ""}\n\n${words(body)}`).join("\n\n")}
`;

writeFileSync(OUT, md);
console.log(`${OUT}: ${parts.length} sections from ${URL_}`);
